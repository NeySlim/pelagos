"""Writes backend/pelagos/data/oui.tsv, the compact OUI table (architecture section 27, decision D7).

Sources: the IEEE Registration Authority public listings (read 2026-11-01), MA-L, MA-M, MA-S and
IAB. Run at each release: `python3 scripts/gen-oui.py` (or `--from <dir>` with the four CSV files).
"""

from __future__ import annotations

import argparse
import csv
import io
import re
import sys
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

BASE = "https://standards-oui.ieee.org"
# (registry file, hex digits of its prefixes)
SOURCES = (("oui/oui.csv", 6), ("oui28/mam.csv", 7), ("oui36/oui36.csv", 9), ("iab/iab.csv", 9))
# The IEEE front end rejects browser user agents; a plain tool name is served.
USER_AGENT = "pelagos-gen-oui/1"
OUT = Path(__file__).resolve().parent.parent / "backend" / "pelagos" / "data" / "oui.tsv"
MAX_BYTES = 2 * 1024 * 1024
NAME_MAX = 48
SKIPPED = {"private", "ieee registration authority"}
# Legal forms dropped from the end of a name, repeatedly ("Foo Co., Ltd." -> "Foo").
SUFFIX = re.compile(
    r"[\s,.]+(co|corp|corporation|company|inc|incorporated|ltd|limited|llc|l\.l\.c|plc|gmbh|ag|kg|"
    r"sa|s\.a|sas|s\.a\.s|sarl|srl|s\.r\.l|spa|s\.p\.a|bv|b\.v|nv|n\.v|oy|ab|as|a/s|aps|kk|k\.k|"
    r"pty|pte|pvt|private|sdn bhd|bhd|s\.l|sl|s\.a\.u|de c\.v|sa de cv|s\.a\. de c\.v|ltda|"
    r"co\.,? ltd|technology co|tech co)\.?$",
    re.IGNORECASE,
)


def short_name(raw: str) -> str:
    name = " ".join(raw.replace("\t", " ").split()).strip(" ,.&")
    while True:
        cut = SUFFIX.sub("", name).strip(" ,.&")
        if cut == name or not cut:
            break
        name = cut
    return name[:NAME_MAX].rstrip(" ,.&")


def rows(text: str, digits: int) -> list[tuple[str, str]]:
    out = []
    for row in csv.DictReader(io.StringIO(text)):
        prefix = (row.get("Assignment") or "").strip().upper()
        name = short_name(row.get("Organization Name") or "")
        if len(prefix) != digits or not re.fullmatch(r"[0-9A-F]+", prefix):
            continue
        if not name or name.lower() in SKIPPED:
            continue
        out.append((prefix, name))
    return out


def fetch(path: str) -> str:
    req = urllib.request.Request(f"{BASE}/{path}", headers={"User-Agent": USER_AGENT})  # noqa: S310
    with urllib.request.urlopen(req, timeout=120) as resp:  # noqa: S310 (fixed https URL)
        return resp.read().decode("utf-8", errors="replace")


def build(texts: dict[str, str], when: str) -> str:
    table: dict[str, str] = {}
    for path, digits in SOURCES:
        for prefix, name in rows(texts[path], digits):
            table.setdefault(prefix, name)
    lines = [
        "# Pelagos OUI table: <hex prefix> TAB <manufacturer>, generated by scripts/gen-oui.py",
        f"# Sources: {', '.join(f'{BASE}/{p}' for p, _ in SOURCES)}",
        f"# Read: {when}; entries: {len(table)}",
    ]
    lines += [f"{p}\t{n}" for p, n in sorted(table.items())]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from", dest="src", type=Path, help="directory holding the four CSV files")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    texts = {}
    for path, _digits in SOURCES:
        texts[path] = (args.src / Path(path).name).read_text(encoding="utf-8") if args.src else fetch(path)
    text = build(texts, datetime.now(UTC).strftime("%Y-%m-%d"))
    size = len(text.encode())
    if size > MAX_BYTES:
        print(f"oui.tsv would be {size} bytes, over {MAX_BYTES}", file=sys.stderr)
        return 1
    args.out.write_text(text, encoding="utf-8")
    print(f"{args.out}: {size} bytes, {text.count(chr(10)) - 3} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
