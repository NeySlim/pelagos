// Administration > Backups against the mock: an SFTP destination whose key is never shown again
// and its test, "Back up now" as a job, the identity shown once on rotation, schedule and
// retention, and a restore through inspect, parts and the plan preview applied as a job.
import { test, expect } from '@playwright/test'

const KEY = '-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXktdjEAAAAA\n-----END OPENSSH PRIVATE KEY-----'

async function signIn(page, username = 'admin', password = 'admin') {
  await page.goto('/login')
  await page.getByTestId('login-username').fill(username)
  await page.getByTestId('login-password').fill(password)
  await page.getByTestId('login-submit').click()
  await expect(page.getByTestId('sidebar')).toBeVisible()
}

test('adds an SFTP destination with a write-only key, tests it, and backs up now', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/archives')
  await expect(page.getByTestId('archives-node')).toHaveCount(2)
  await page.getByTestId('archives-dest-add').click()
  const dialog = page.getByTestId('archives-dest-dialog')
  await dialog.locator('#archives-dest-type').click()
  await page.getByRole('option', { name: 'SFTP' }).click()
  await dialog.getByTestId('archives-dest-name').fill('Off site e2e')
  await dialog.getByTestId('archives-dest-host').fill('backup.example.lan')
  await dialog.getByTestId('archives-dest-username').fill('pelagos')
  await dialog.getByTestId('archives-dest-fingerprint').fill(`SHA256:${'A'.repeat(43)}`)
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog.getByText('Required')).toBeVisible()
  await dialog.getByTestId('archives-dest-key').fill(KEY)
  await dialog.getByTestId('archives-dest-test').click()
  await expect(dialog.getByTestId('archives-dest-test-result')).toHaveAttribute('data-ok', 'true')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()

  const card = page.getByTestId('archives-dest').filter({ hasText: 'Off site e2e' })
  await expect(card).toContainText('pelagos@backup.example.lan:22/.')
  await card.getByTestId('archives-dest-edit').click()
  await expect(dialog.getByTestId('archives-dest-key')).toHaveValue('')
  await dialog.getByTestId('archives-dest-host').fill('unreachable.example.lan')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toContainText('The server changed: enter the key again')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.locator('body')).not.toContainText('b3BlbnNzaC1rZXktdjEAAAAA')

  const before = await page.getByTestId('archives-table').locator('tbody tr').count()
  await page.getByTestId('archives-run').click()
  await expect(page.getByTestId('archives-run-job')).toHaveAttribute('data-state', 'done')
  await expect(page.getByTestId('archives-run-step')).toHaveCount(2)
  await expect.poll(() => page.getByTestId('archives-table').locator('tbody tr').count()).toBeGreaterThan(before)

  await card.getByTestId('archives-dest-delete').click()
  await page.getByRole('button', { name: 'Delete', exact: true }).last().click()
  await expect(card).toHaveCount(0)
})

test('rotates the key behind the password and shows the identity once', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/archives')
  await page.getByTestId('archives-key-rotate').click()
  const dialog = page.getByTestId('archives-password-dialog')
  await dialog.getByTestId('archives-password').fill('wrong')
  await dialog.getByRole('button', { name: 'Rotate' }).click()
  await expect(dialog).toContainText('Wrong password')
  await dialog.getByTestId('archives-password').fill('admin')
  await dialog.getByRole('button', { name: 'Rotate' }).click()
  const once = page.getByTestId('archives-identity-once')
  await expect(once.getByTestId('archives-identity-value')).toContainText('AGE-SECRET-KEY-1')
  await expect(once.getByTestId('archives-identity-close')).toBeDisabled()
  await once.getByTestId('archives-identity-saved').check()
  await once.getByTestId('archives-identity-close').click()
  await expect(once).toBeHidden()
  await expect(page.getByTestId('archives-retired')).toContainText('1 former identity')
})

test('turns scheduling on and off, and saves the retention', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/archives')
  const toggle = page.getByTestId('archives-schedule-toggle').getByRole('switch')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByTestId('archives-node').first()).not.toContainText('Not scheduled')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await page.getByTestId('archives-setting-keep_daily_count').fill('400')
  await expect(page.getByTestId('archives-schedule')).toContainText('From 0 to 366')
  await expect(page.getByTestId('archives-settings-save')).toBeDisabled()
  await page.getByTestId('archives-setting-keep_daily_count').fill('14')
  await page.getByTestId('archives-settings-save').click()
  await expect(page.getByTestId('archives-settings-save')).toBeHidden()
  await page.reload()
  await expect(page.getByTestId('archives-setting-keep_daily_count')).toHaveValue('14')
})

test('restores parts of an archive through the plan preview', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/archives')
  await page.getByTestId('archives-restore-open').first().click()
  const wizard = page.getByTestId('archives-restore')
  await expect(wizard).toHaveAttribute('data-step', 'source')
  await wizard.getByTestId('archives-restore-identity').fill('not an identity')
  await expect(wizard.getByTestId('archives-restore-inspect')).toBeDisabled()
  await wizard.getByTestId('archives-restore-identity').fill('')
  await wizard.getByTestId('archives-restore-inspect').click()
  await expect(wizard).toHaveAttribute('data-step', 'parts')
  await expect(wizard.getByTestId('archives-restore-part')).toHaveCount(8)
  const zone = wizard.locator('[data-part="bind.zone:_default/example.lan"]')
  await expect(zone).toContainText('2 added, 1 replaced, 0 deleted')
  await expect(zone.getByRole('checkbox')).toBeChecked()
  await wizard.locator('[data-part="bind.user_files"]').getByRole('checkbox').check()
  await expect(wizard.getByTestId('archives-restore-build')).toBeDisabled()
  await wizard.getByTestId('archives-restore-userfiles-1').check()
  await wizard.getByTestId('archives-restore-userfiles-2').check()
  await wizard.locator('[data-part="bind.user_files"]').getByRole('checkbox').uncheck()
  await wizard.getByTestId('archives-restore-build').click()
  await expect(wizard).toHaveAttribute('data-step', 'plan')
  const plan = wizard.getByTestId('plan-preview')
  await expect(plan.getByTestId('plan-summary')).toContainText('restore from the archive')
  await expect(plan.getByTestId('plan-apply')).toBeDisabled()
  await plan.getByTestId('plan-confirm-checkbox').check()
  await plan.getByTestId('plan-apply').click()
  await expect(plan.getByTestId('plan-job')).toBeVisible()
  await expect(plan).toHaveAttribute('data-plan-state', 'applied', { timeout: 20000 })
})
