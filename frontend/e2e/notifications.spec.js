// Administration > Notifications against the mock: a channel added with a write-only secret,
// test sends (ok and failing), the global mute seen from the alerts, the sender order, a failing
// channel surfaced with its notification_failed alert, and the /alerts?alert=<id> link.
import { test, expect } from '@playwright/test'

const event = (page, kind, extra = {}) => page.request.post('/api/v1/_mock/events', { data: { kind, ...extra } }).then((r) => r.json())

async function signIn(page, username = 'admin', password = 'admin') {
  await page.goto('/login')
  await page.getByTestId('login-username').fill(username)
  await page.getByTestId('login-password').fill(password)
  await page.getByTestId('login-submit').click()
  await expect(page.getByTestId('sidebar')).toBeVisible()
}

test('adds a Gotify channel whose token is never shown again, and tests it', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/notifications')
  await expect(page.getByTestId('notify-channel').first()).toContainText('Phone (ntfy)')
  await page.getByTestId('notify-add').click()
  const dialog = page.getByTestId('notify-channel-dialog')
  await dialog.locator('#notify-type').click()
  await page.getByRole('option', { name: 'Gotify' }).click()
  await dialog.getByTestId('notify-name').fill('Gotify e2e')
  await dialog.getByTestId('notify-url').fill('https://gotify.example.lan')
  await page.getByTestId('notify-dialog-save').click()
  await expect(dialog).toContainText('Fix the highlighted fields')
  await dialog.getByTestId('notify-secret-token').fill('A1b2C3d4')
  await page.getByTestId('notify-dialog-test').click()
  await expect(dialog.getByTestId('notify-test-result')).toHaveAttribute('data-ok', 'true')
  await page.getByTestId('notify-dialog-save').click()
  await expect(dialog).toBeHidden()

  const card = page.getByTestId('notify-channel').filter({ hasText: 'Gotify e2e' })
  await expect(card.getByTestId('notify-channel-state')).toHaveText('OK')
  await card.getByTestId('notify-channel-test').click()
  await expect(card.getByTestId('notify-channel-test-result')).toHaveAttribute('data-ok', 'true')
  await card.getByTestId('notify-channel-edit').click()
  await expect(dialog.getByTestId('notify-secret-token')).toHaveValue('')
  await expect(dialog).toContainText('Enter a new value to change it')
  await expect(page.locator('body')).not.toContainText('A1b2C3d4')
  await dialog.getByRole('button', { name: 'Cancel' }).click()

  await card.getByTestId('notify-channel-delete').click()
  await page.getByRole('button', { name: 'Delete', exact: true }).last().click()
  await expect(card).toHaveCount(0)
})

test('asks for the token again when a channel moves, and shows the error of a failing test', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/notifications')
  await page.locator('[data-testid="notify-channel"][data-channel="ch-ntfy"]').getByTestId('notify-channel-edit').click()
  const dialog = page.getByTestId('notify-channel-dialog')
  await dialog.getByTestId('notify-url').fill('https://unreachable.example.lan')
  await page.getByTestId('notify-dialog-test').click()
  await expect(dialog).toContainText('The server changed: enter the secret again or remove it')
  await dialog.getByTestId('notify-secret-token').fill('tk_other')
  await page.getByTestId('notify-dialog-test').click()
  const result = dialog.getByTestId('notify-test-result')
  await expect(result).toHaveAttribute('data-ok', 'false')
  await expect(result).toContainText('connection failed')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
})

test('mutes every channel with a reason, seen from the alerts page, then lifts it', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/notifications')
  await page.getByTestId('notify-mute').click()
  await page.getByTestId('notify-mute-comment').fill('kernel upgrade on ns2')
  await page.getByTestId('notify-mute-dialog').getByRole('button', { name: 'Mute notifications' }).click()
  await expect(page.getByTestId('notify-mute-banner')).toContainText('kernel upgrade on ns2')
  await page.goto('/alerts')
  await expect(page.getByTestId('alerts-notify-muted')).toContainText('kernel upgrade on ns2')
  await page.goto('/admin/notifications')
  await page.getByTestId('notify-unmute').click()
  await page.getByRole('button', { name: 'Lift the mute' }).last().click()
  await expect(page.getByTestId('notify-mute-banner')).toHaveCount(0)
  await expect(page.getByTestId('notify-mute-state')).toContainText('Off')
})

test('reorders the sending nodes', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/notifications')
  const nodes = page.getByTestId('notify-order-node')
  const first = await nodes.first().getAttribute('data-node')
  await nodes.first().getByTestId('notify-order-down').click()
  await page.getByTestId('notify-order-save').click()
  await expect(nodes.nth(1)).toHaveAttribute('data-node', first)
  await nodes.nth(1).getByTestId('notify-order-up').click()
  await page.getByTestId('notify-order-save').click()
  await expect(nodes.first()).toHaveAttribute('data-node', first)
})

test('surfaces a failing channel and its alert, opened through the alert link', async ({ page }) => {
  await signIn(page)
  await page.goto('/admin/notifications')
  const out = await event(page, 'notify-fail', { channel_id: 'ch-ntfy' })
  const card = page.locator('[data-testid="notify-channel"][data-channel="ch-ntfy"]')
  await expect(card).toHaveAttribute('data-state', 'failing')
  await expect(card.getByTestId('notify-channel-error')).toContainText('HTTP 401')
  await expect(page.getByTestId('notify-history-table')).toContainText('Failed')
  const failed = page.getByTestId('notify-failed-alert')
  await expect(failed).toContainText('Phone (ntfy)')
  await failed.getByTestId('notify-failed-open').click()
  await expect(page).toHaveURL(new RegExp(`/alerts\\?alert=${out.id}`))
  const detail = page.getByTestId('alert-detail')
  await expect(detail).toContainText(`notify:ch-ntfy`)
  await detail.getByTestId('alert-open-subject').click()
  await expect(page).toHaveURL(/\/admin\/notifications\?channel=ch-ntfy/)
  await event(page, 'notify-recover', { channel_id: 'ch-ntfy' })
  await expect(card).toHaveAttribute('data-state', 'ok')
  await expect(page.getByTestId('notify-failed-alerts')).toHaveCount(0)
})

test('opens an alert from a notification link and says where it was sent', async ({ page }) => {
  await signIn(page)
  await page.goto('/alerts?alert=ALRT0000000000000000000005')
  const detail = page.getByTestId('alert-detail')
  await expect(detail).toContainText('key:rndc-key')
  await expect(detail.getByTestId('alert-notified')).toContainText('Phone (ntfy)')
  await page.keyboard.press('Escape')
  await expect(detail).toBeHidden()
  await expect(page).not.toHaveURL(/alert=/)
})
